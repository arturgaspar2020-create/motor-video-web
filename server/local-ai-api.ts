import type { Plugin } from "vite";

const OLLAMA_URL = "http://127.0.0.1:11434";
const MODEL = "qwen3:4b";

type SceneInput = { id: number; type: string; name: string; directives: string[]; narration: string; sentences: string[]; autoGenerated?: boolean };
type ShotPlan = { action: string; camera: string; objects: string[]; environment: string; character: string; emotion: string };

function parseScenes(script: string): SceneInput[] {
  const sourceLines = script.replace(/\r/g, "").split("\n");
  const hasSceneHeaders = sourceLines.some(line => /^\s*\[cena:\s*/i.test(line));
  const scenes: SceneInput[] = [];
  let current: SceneInput | null = null;
  const flush = () => {
    if (!current) return;
    current.narration = current.narration.trim();
    current.sentences = current.narration.split(/(?<=[.!?…])\s+/).map(value => value.trim()).filter(Boolean);
    scenes.push(current);
    current = null;
  };

  if (!hasSceneHeaders) {
    // Plain narration is automatically divided into short visual scenes.
    const paragraphs = sourceLines
      .map(line => line.trim())
      .filter(line => line && !/^@(idioma|titulo)\s+/i.test(line))
      .join("\n")
      .split(/\n+/)
      .map(value => value.trim())
      .filter(Boolean);
    const sentences = paragraphs.flatMap(paragraph =>
      paragraph.split(/(?<=[.!?…])\s+/).map(value => value.trim()).filter(Boolean)
    );
    for (let index = 0; index < sentences.length; index += 2) {
      const group = sentences.slice(index, index + 2);
      const narration = group.join(" ");
      scenes.push({
        id: scenes.length + 1,
        type: "narrativa",
        name: "Cena " + String(scenes.length + 1).padStart(2, "0"),
        directives: [],
        narration,
        sentences: group,
        autoGenerated: true
      });
    }
    return scenes;
  }

  for (const line of sourceLines) {
    const value = line.trim();
    const match = value.match(/^\[cena:\s*([^\]|]+)(?:\|\s*([^\]]+))?\]$/i);
    if (match) {
      flush();
      current = { id: scenes.length + 1, type: match[1].trim(), name: (match[2] || match[1]).trim(), directives: [], narration: "", sentences: [] };
      continue;
    }
    if (!current || !value) continue;
    if (/^\[shot:\s*\{/i.test(value)) continue;
    if (/^\[[^\]]+\]$/.test(value)) current.directives.push(value);
    else current.narration += (current.narration ? "\n" : "") + value;
  }
  flush();
  return scenes;
}

function directiveValue(scene: SceneInput, keys: string[]): string {
  for (const key of keys) {
    const normalized = key.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
    const line = [...scene.directives].reverse().find(item => {
      const match = item.match(/^\[([^:]+):\s*([^\]]*)\]$/);
      return match?.[1].trim().normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase() === normalized.toLowerCase();
    });
    if (line) return line.slice(line.indexOf(":") + 1, -1).trim();
  }
  return "";
}

function directiveList(value: string): string[] {
  return value.split(/[,;\n]+|\s+e\s+/i).map(item => item.trim()).filter(Boolean).slice(0, 12);
}

function inferAction(text: string): string {
  const rules: Array<[string, RegExp]> = [
    ["running", /\b(run|runs|running|ran|sprint|corr(?:e|eu|endo|er)|fug(?:e|iu|indo|ir)|rennt|rennen)\b/i],
    ["walking", /\b(walk|walks|walking|walked|caminh(?:a|ou|ando|ar)|and(?:a|ou|ando)|geht|ging)\b/i],
    ["opening", /\b(open|opens|opened|opening|abr(?:e|iu|indo|ir)|öffnet|oeffnet)\b/i],
    ["closing", /\b(close|closes|closed|closing|fech(?:a|ou|ando|ar)|schließt)\b/i],
    ["picking up", /\b(pick(?:s)? up|picked up|grab(?:s|bed)?|take(?:s)?|took|peg(?:a|ou|ando)|apanh(?:a|ou|ando))\b/i],
    ["dropping", /\b(drop(?:s|ped)?|falls?|fell|falling|derrub(?:a|ou|ando)|cai(?:u|ndo))\b/i],
    ["sitting", /\b(sit(?:s|ting)?|sat|senta(?:-se|r)?|sentou|sentado)\b/i],
    ["standing", /\b(stand(?:s|ing)?|stood|levanta(?:-se|r)?|levantou)\b/i],
    ["jumping", /\b(jump(?:s|ed|ing)?|salta(?:r|ou|ndo)?|pula(?:r|ou|ndo)?)\b/i],
    ["turning", /\b(turn(?:s|ed|ing)?|vira(?:-se|r)?|virou|gira(?:r|ou)?)\b/i],
    ["pressing", /\b(press(?:es|ed|ing)?|push(?:es|ed|ing)?|aperta(?:r|ou|ndo)?|pressiona(?:r|ou|ndo)?)\b/i],
    ["pointing", /\b(point(?:s|ed|ing)?|apont(?:a|ou|ando))\b/i],
    ["looking", /\b(look(?:s|ed|ing)?|watch(?:es|ed)?|observ(?:a|ou|ando)|olha(?:r|ou|ndo)?|encara)\b/i],
    ["reacting", /\b(flicker(?:s|ed|ing)?|blink(?:s|ed|ing)?|pisca(?:r|ou|ndo)?|solavanco|para bruscamente|stops?|stopped|reag(?:e|iu|indo)|assust(?:a|ou|ado))\b/i],
    ["waving", /\b(wav(?:e|es|ed|ing)|acen(?:a|ou|ando))\b/i]
  ];
  for (const [action, pattern] of rules) if (pattern.test(text)) return action;
  return "none";
}

function normalizeAction(value: unknown, narration: string, sceneAction: string): string {
  const directiveAction = inferAction(sceneAction);
  if (directiveAction !== "none") return directiveAction;
  const raw = String(value || "").toLowerCase().trim();
  const allowed = new Set(["idle","walking","running","opening","closing","picking up","dropping","sitting","standing","jumping","turning","looking","reacting","pointing","pressing","waving","fighting","climbing","swimming","hiding","driving","riding","talking","searching","crawling","kneeling","pushing","pulling","carrying","aiming","shooting","none"]);
  if (allowed.has(raw) && raw !== "none") return raw;
  return inferAction(narration);
}

function normalizeCamera(value: unknown): string {
  const raw = String(value || "").trim();
  if (!raw) return "medium shot";
  const lower = raw.toLowerCase();
  if (/plano\s+aberto|plano\s+geral|wide shot|establishing/.test(lower)) return "wide shot";
  if (/plano\s+m[eé]dio|medium shot/.test(lower)) return "medium shot";
  if (/close.?up|primeiro plano|detalhe/.test(lower)) return "close-up";
  if (/sobre o ombro|over.?the.?shoulder/.test(lower)) return "over-the-shoulder";
  if (/ponto de vista|point.?of.?view|subjetiva/.test(lower)) return "point-of-view";
  if (/c[aâ]mera tremendo|handheld|tremida/.test(lower)) return "handheld tracking shot";
  if (/de baixo|low angle/.test(lower)) return "low angle";
  if (/a[eé]rea|de cima|aerial|overhead/.test(lower)) return "aerial shot";
  return raw.slice(0, 120);
}

function applyGeneratedSceneMarkers(scenes: SceneInput[], plans: ShotPlan[][], generatedNames: string[], sourceScript: string): string {
  const metadata = sourceScript.replace(/\r/g, "").split("\n")
    .map(line => line.trim())
    .filter(line => /^@(idioma|titulo)\s+/i.test(line));
  const output = [...metadata, ""];
  scenes.forEach((scene, sceneIndex) => {
    const proposedName = String(generatedNames[sceneIndex] || scene.name)
      .replace(/[\[\]\r\n|]/g, " ")
      .replace(/\s+/g, " ")
      .trim()
      .slice(0, 70) || ("Cena " + String(sceneIndex + 1).padStart(2, "0"));
    output.push("[cena: narrativa | " + proposedName + "]");
    scene.sentences.forEach((sentence, shotIndex) => {
      const plan = plans[sceneIndex]?.[shotIndex];
      if (plan) output.push("[shot: " + JSON.stringify(plan) + "]");
      output.push(sentence);
    });
    output.push("");
  });
  return output.join("\n").trim();
}

function applyShotMarkers(script: string, scenes: SceneInput[], plans: ShotPlan[][]): string {
  const lines = script.replace(/\r/g, "").split("\n");
  const output: string[] = [];
  let sceneIndex = -1;
  let sentenceIndex = 0;
  let narrationLines: string[] = [];
  const flushNarration = () => {
    if (!narrationLines.length || sceneIndex < 0) return;
    const raw = narrationLines.join(" ").trim();
    const sentences = raw.split(/(?<=[.!?…])\s+/).map(value => value.trim()).filter(Boolean);
    for (const sentence of sentences) {
      const plan = plans[sceneIndex]?.[sentenceIndex];
      if (plan) output.push("[shot: " + JSON.stringify(plan) + "]");
      output.push(sentence);
      sentenceIndex++;
    }
    narrationLines = [];
  };
  for (const line of lines) {
    const value = line.trim();
    const header = value.match(/^\[cena:\s*([^\]|]+)(?:\|\s*([^\]]+))?\]$/i);
    if (header) {
      flushNarration();
      sceneIndex++;
      sentenceIndex = 0;
      output.push(line);
      continue;
    }
    if (sceneIndex >= 0 && /^\[shot:\s*\{/i.test(value)) { flushNarration(); continue; }
    if (sceneIndex >= 0 && /^\[[^\]]+\]$/.test(value)) {
      flushNarration();
      if (!/^\[shot:/i.test(value)) output.push(line);
      continue;
    }
    if (sceneIndex >= 0 && value) narrationLines.push(value);
    else {
      flushNarration();
      output.push(line);
    }
  }
  flushNarration();
  return output.join("\n");
}

async function readJsonBody(req: any): Promise<any> {
  const chunks: Buffer[] = [];
  for await (const chunk of req) chunks.push(Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk));
  const raw = Buffer.concat(chunks).toString("utf8");
  return raw ? JSON.parse(raw) : {};
}

export function localAiApi(): Plugin {
  return {
    name: "motor-video-local-ai",
    configureServer(server) {
      server.middlewares.use("/api/ai", (req, res) => {
        const send = (code: number, data: unknown) => {
          res.statusCode = code;
          res.setHeader("Content-Type", "application/json; charset=utf-8");
          res.setHeader("Cache-Control", "no-store");
          res.end(JSON.stringify(data));
        };
        const route = (req.url || "/").split("?")[0];
        if (req.method === "GET" && route === "/status") {
          void (async () => {
            try {
              const response = await fetch(OLLAMA_URL + "/api/tags", { signal: AbortSignal.timeout(3500) });
              if (!response.ok) throw new Error("Ollama não respondeu corretamente.");
              const data = await response.json() as { models?: { name: string }[] };
              const models = (data.models || []).map(item => item.name);
              const installed = models.some(name => name === MODEL || name.startsWith(MODEL + ":"));
              send(200, { online: true, model: MODEL, installed, models });
            } catch {
              send(200, { online: false, model: MODEL, installed: false, models: [] });
            }
          })();
          return;
        }
        if (req.method !== "POST" || route !== "/analyze") {
          send(404, { error: "Rota de IA não encontrada." });
          return;
        }
        void (async () => {
          try {
            const body = await readJsonBody(req);
            const script = typeof body.script === "string" ? body.script : "";
            if (!script.trim()) { send(400, { error: "Cole um roteiro antes de analisar." }); return; }
            if (script.length > 50000) { send(413, { error: "O roteiro ultrapassa 50 mil caracteres. Divida em partes menores." }); return; }
            const scenes = parseScenes(script);
            if (!scenes.length) { send(400, { error: "Não encontrei cenas. Use [cena: tipo | nome] antes de cada cena." }); return; }
            const missing = scenes.filter(scene => !scene.sentences.length);
            if (missing.length) { send(400, { error: "A cena " + missing[0].id + " não tem narração para analisar." }); return; }
            const status = await fetch(OLLAMA_URL + "/api/tags", { signal: AbortSignal.timeout(3500) }).catch(() => null);
            if (!status?.ok) { send(503, { error: "Ollama não está aberto. Instale e inicie o Ollama; depois clique em Verificar IA." }); return; }
            const tags = await status.json() as { models?: { name: string }[] };
            if (!(tags.models || []).some(item => item.name === MODEL || item.name.startsWith(MODEL + ":"))) {
              send(409, { error: "O modelo " + MODEL + " ainda não foi baixado. Execute o arquivo instalar-ia-local.bat na pasta do projeto." });
              return;
            }
            const input = scenes.map(scene => ({
              id: scene.id, scene_type: scene.type, scene_name: scene.name,
              existing_directives: scene.directives, shots: scene.sentences.map((text, index) => ({ index, narration: text }))
            }));
            const system = [
              "Você é o diretor de animação 3D do Motor Video Studio.",
              "Analise as cenas e cada frase de narração. Responda SOMENTE JSON válido, sem markdown. Quando scene_type for narrativa e scene_name começar com Cena, crie um nome visual curto e específico para a cena, no mesmo idioma da narração.",
              "As diretivas existentes em existing_directives são instruções do usuário e têm prioridade sobre inferências genéricas. Leia [acao:], [elementos:], [ambiente:], [personagem:], [camera:] e [animacao:] e aplique seus valores aos shots correspondentes.",
              "Se uma diretiva definir a ação da cena, use-a para escolher uma ação visual compatível em cada frase; não retorne action=none quando a diretiva ou a narração indicar uma ação.",
              "Inclua os objetos de [elementos:] em objects em todos os shots da cena. Use [ambiente:] em environment, [personagem:] em character e [camera:] em camera. Não descarte esses marcadores.",
              "Retorne exatamente um item por cena e exatamente um shot por frase, na mesma ordem. Inclua scene_name em cada cena; em roteiros livres, scene_name deve descrever visualmente o momento narrado sem inventar fatos.",
              "Não reescreva, resuma ou traduza a narração. Não invente acontecimentos que não estejam implicados no texto.",
              "Para action use apenas: idle, walking, running, opening, closing, picking up, dropping, sitting, standing, jumping, turning, looking, reacting, pointing, waving, fighting, climbing, swimming, hiding, driving, riding, talking, searching, crawling, kneeling, pushing, pulling, carrying, aiming, shooting, none. Para apertar ou pressionar fisicamente um botão, use pressing; use pointing somente para apontar. Para luzes piscando, pane ou susto, use reacting.",
              "Escolha a ação principal visível da frase. Use none se não houver ação humana clara.",
              "camera deve ser uma instrução curta em inglês: wide shot, medium shot, close-up, tracking shot, over-the-shoulder, low angle, aerial shot, point-of-view, reaction close-up ou uma combinação simples.",
              "objects deve conter apenas objetos concretos mencionados ou claramente necessários na frase, com nomes simples em inglês.",
              "environment deve ser uma descrição curta em inglês apenas se o local estiver explícito; caso contrário string vazia.",
              "character deve ser uma descrição curta em inglês se houver personagem identificável; caso contrário string vazia.",
              "emotion deve ser uma emoção visual curta em inglês ou string vazia.",
              "Não crie personagens, objetos ou cenas sem base na narração.",
              'Formato: {"scenes":[{"id":1,"scene_name":"O explorador encontra o mapa","shots":[{"action":"walking","camera":"tracking shot","objects":["flashlight"],"environment":"foggy forest","character":"explorer","emotion":"alert"}]}]}'
            ].join(" ");
            const response = await fetch(OLLAMA_URL + "/api/chat", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({
                model: MODEL, stream: false, format: "json", think: false, keep_alive: "10m",
                options: { temperature: 0.15, num_ctx: 8192 },
                messages: [
                  { role: "system", content: system },
                  { role: "user", content: JSON.stringify(input) }
                ]
              }),
              signal: AbortSignal.timeout(15 * 60 * 1000)
            });
            if (!response.ok) {
              const detail = await response.text();
              throw new Error("Ollama retornou erro: " + detail.slice(0, 500));
            }
            const result = await response.json() as { message?: { content?: string } };
            const parsed = JSON.parse(result.message?.content || "{}") as { scenes?: { id?: number; scene_name?: string; shots?: Partial<ShotPlan>[] }[] };
            if (!Array.isArray(parsed.scenes) || parsed.scenes.length !== scenes.length) {
              throw new Error("A IA retornou uma quantidade de cenas diferente do roteiro. Tente novamente.");
            }
            const plans: ShotPlan[][] = scenes.map((scene, index) => {
              const returned = parsed.scenes![index];
              if (!Array.isArray(returned.shots) || returned.shots.length !== scene.sentences.length) {
                throw new Error("A IA não retornou uma análise para cada frase da cena " + scene.id + ". Tente novamente.");
              }
              const sceneAction = directiveValue(scene, ["acao", "movimento"]);
              const sceneElements = directiveList(directiveValue(scene, ["elementos", "objetos"]));
              const sceneEnvironment = directiveValue(scene, ["ambiente", "local"]);
              const sceneCharacter = directiveValue(scene, ["personagem", "personagens"]);
              const sceneCamera = directiveValue(scene, ["camera", "câmera", "enquadramento"]);
              const sceneAnimation = directiveValue(scene, ["animacao", "animação"]);
              return returned.shots.map((item, shotIndex) => {
                const narration = scene.sentences[shotIndex];
                const action = normalizeAction(item.action, narration, sceneAction || sceneAnimation);
                const aiObjects = Array.isArray(item.objects) ? item.objects.map(value => String(value).trim()).filter(Boolean) : [];
                const sceneIsElevator = /elevator|elevador|lift|aufzug/i.test(scene.name);
                return {
                  action: action.slice(0, 40),
                  camera: normalizeCamera(item.camera || sceneCamera),
                  objects: (sceneElements.length ? sceneElements : aiObjects).slice(0, 12).map(value => value.slice(0, 60)),
                  environment: String(sceneEnvironment || item.environment || (sceneIsElevator ? "interior of a modern elevator" : "")).slice(0, 120),
                  character: String(item.character || sceneCharacter || "").slice(0, 100),
                  emotion: String(item.emotion || (/(medo|assust|pânico|panic|surpres|surprise)/i.test(sceneAnimation) ? "fear" : "")).slice(0, 60)
                };
              });
            });
            const generatedNames = parsed.scenes!.map((item, index) => String(item.scene_name || scenes[index].name));
            const isPlainNarration = scenes.every(scene => scene.autoGenerated);
            const enhancedScript = isPlainNarration
              ? applyGeneratedSceneMarkers(scenes, plans, generatedNames, script)
              : applyShotMarkers(script, scenes, plans);
            const actionCount = plans.flat().filter(item => item.action !== "none" && item.action !== "idle").length;
            const objectCount = new Set(plans.flat().flatMap(item => item.objects)).size;
            send(200, {
              ok: true, model: MODEL, enhancedScript,
              summary: { scenes: scenes.length, shots: plans.reduce((sum, item) => sum + item.length, 0), actions: actionCount, objects: objectCount },
              plan: scenes.map((scene, index) => ({ id: scene.id, name: scene.name, shots: scene.sentences.map((narration, shotIndex) => ({ narration, ...plans[index][shotIndex] })) }))
            });
          } catch (error) {
            const message = error instanceof Error ? error.message : "Falha ao analisar o roteiro.";
            send(500, { error: message });
          }
        })();
      });
    }
  };
}
